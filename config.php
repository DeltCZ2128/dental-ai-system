/* Auto-mark missed appointments as No-Show (no manual click needed).
 * - Past dates still Pending/Confirmed -> No-Show
 * - Today: 30-min grace after end_time, then Pending/Confirmed -> No-Show */
function markClosedAppointmentsAsNoShow()
{
    global $pdo;

    try {
        /* If the system clock was moved forward for testing and then rewound,
         * any appointment whose scheduled window is still in the future cannot
         * yet be a No-Show. Restore it to Confirmed and remove the premature
         * system No-Show notification. */
        $futureNoShowStmt = $pdo->prepare("
            SELECT id
            FROM appointments
            WHERE (
                appointment_date > CURDATE()
                OR (
                    appointment_date = CURDATE()
                    AND end_time > SUBTIME(CURTIME(), '0:30:00')
                )
            )
            AND status = 'No-Show'
        ");
        $futureNoShowStmt->execute();
        $futureNoShows = $futureNoShowStmt->fetchAll(PDO::FETCH_COLUMN);

        if (!empty($futureNoShows)) {
            $restoreStmt = $pdo->prepare("
                UPDATE appointments
                SET status = 'Confirmed'
                WHERE id = ? AND status = 'No-Show'
            ");
            $delNotifStmt = $pdo->prepare("
                DELETE FROM notifications
                WHERE appointment_id = ? AND title = 'No-Show' AND type = 'System'
            ");
            foreach ($futureNoShows as $fid) {
                $restoreStmt->execute([(int)$fid]);
                $delNotifStmt->execute([(int)$fid]);
            }
        }

        $stmt = $pdo->prepare("
            SELECT id, patient_id, appointment_date, start_time
            FROM appointments
            WHERE (
                appointment_date < CURDATE()
                OR (
                    appointment_date = CURDATE()
                    AND end_time <= SUBTIME(CURTIME(), '0:30:00')
                )
            )
            AND status IN ('Confirmed', 'Approved')
        ");

        $stmt->execute();
        $missed = $stmt->fetchAll(PDO::FETCH_ASSOC);

        if (empty($missed)) {
            return;
        }

        $markStmt = $pdo->prepare("
            UPDATE appointments
            SET status = 'No-Show'
            WHERE id = ?
            AND status IN ('Confirmed', 'Approved')
        ");

        $checkStmt = $pdo->prepare("
            SELECT id
            FROM notifications
            WHERE appointment_id = ?
            AND title = 'No-Show'
            LIMIT 1
        ");

        $notifyStmt = $pdo->prepare("
            INSERT INTO notifications
            (patient_id, appointment_id, title, message, type)
            VALUES (?, ?, ?, ?, ?)
        ");

        foreach ($missed as $appt) {
            $markStmt->execute([(int)$appt['id']]);

            if ($markStmt->rowCount() > 0) {
                try {
                    $checkStmt->execute([(int)$appt['id']]);

                    if (!$checkStmt->fetch()) {
                        $notifyStmt->execute([
                            (int)$appt['patient_id'],
                            (int)$appt['id'],
                            'No-Show',
                            'You were automatically marked as No-Show for your appointment on ' . $appt['appointment_date'] . ' at ' . substr($appt['start_time'], 0, 5) . '. Please contact the clinic to reschedule.',
                            'System'
                        ]);
                    }
                } catch (PDOException $e) {
                    // Notification failure must not block status update.
                }
            }
        }
    } catch (PDOException $e) {
        // The appointments table may not exist during initial setup.
    }
}

