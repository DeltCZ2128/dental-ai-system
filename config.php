/* Keep patients.email and patients.contact_number synchronized with linked users accounts
 * and ensure every patient user has a linked patients profile row. */
function autoSyncPatientProfiles()
{
    global $pdo;

    try {
        $pdo->exec("
            UPDATE patients p
            INNER JOIN users u ON u.id = p.user_id
            SET
                p.email = CASE
                    WHEN (p.email IS NULL OR TRIM(p.email) = '') AND u.username LIKE '%@%' THEN TRIM(u.username)
                    ELSE p.email
                END,
                p.contact_number = CASE
                    WHEN (p.contact_number IS NULL OR TRIM(p.contact_number) = '') AND u.contact_number IS NOT NULL AND TRIM(u.contact_number) <> '' THEN TRIM(u.contact_number)
                    ELSE p.contact_number
                END
            WHERE p.user_id IS NOT NULL AND p.user_id > 0
        ");

        $unlinkedUsers = $pdo->query("
            SELECT u.id, u.username, u.full_name, u.contact_number
            FROM users u
            LEFT JOIN patients p ON p.user_id = u.id
            WHERE u.role = 'patient' AND p.id IS NULL
        ")->fetchAll(PDO::FETCH_ASSOC);

        if (!empty($unlinkedUsers)) {
            $findByEmailOrName = $pdo->prepare("
                SELECT id FROM patients
                WHERE (email <> '' AND email = ?)
                   OR (LOWER(TRIM(CONCAT(first_name, ' ', last_name))) = LOWER(TRIM(?)))
                LIMIT 1
            ");
            $linkStmt = $pdo->prepare("
                UPDATE patients
                SET user_id = ?,
                    email = CASE WHEN email IS NULL OR TRIM(email) = '' THEN ? ELSE email END,
                    contact_number = CASE WHEN contact_number IS NULL OR TRIM(contact_number) = '' THEN ? ELSE contact_number END
                WHERE id = ?
            ");
            $insertStmt = $pdo->prepare("
                INSERT INTO patients (user_id, patient_number, first_name, last_name, contact_number, email, status)
                VALUES (?, ?, ?, ?, ?, ?, 'Active')
            ");

            foreach ($unlinkedUsers as $u) {
                $uid = (int)$u['id'];
                $uEmail = (strpos((string)$u['username'], '@') !== false) ? trim((string)$u['username']) : '';
                $uPhone = trim((string)($u['contact_number'] ?? ''));
                $uFull = trim((string)($u['full_name'] ?? 'Patient'));
                $parts = preg_split('/\s+/', $uFull);
                $fName = $parts[0] ?? 'Patient';
                $lName = count($parts) > 1 ? implode(' ', array_slice($parts, 1)) : '';

                $findByEmailOrName->execute([$uEmail, $uFull]);
                $existingId = (int)$findByEmailOrName->fetchColumn();

                if ($existingId > 0) {
                    $linkStmt->execute([$uid, $uEmail, $uPhone, $existingId]);
                } else {
                    $pNum = 'PAT-' . date('Ymd') . '-' . strtoupper(substr(md5($uid . uniqid('', true)), 0, 5));
                    $insertStmt->execute([$uid, $pNum, $fName, $lName, $uPhone, $uEmail]);
                }
            }
        }
    } catch (Throwable $e) {
    }
}

