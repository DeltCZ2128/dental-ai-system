/*
|--------------------------------------------------------------------------
| CSRF PROTECTION
|--------------------------------------------------------------------------
| A single unpredictable token is kept in the session and is written into
| every state-changing form with csrfField(). Before the form is processed,
| the receiving page calls requireCsrf() or csrfValid() to compare the token
| that arrived with the one held in the session. A request that carries no
| token, or a token that does not match, is rejected. This stops a
| logged-in user from being made to submit a form from another page.
*/

/**
 * Return the token of the current session, creating it on first use.
 */
function csrfToken()
{
    if (
        empty($_SESSION['csrf_token']) ||
        !is_string($_SESSION['csrf_token'])
    ) {
        $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
    }

    return $_SESSION['csrf_token'];
}

/**
 * Return the hidden input that carries the token into a form.
 */
function csrfField()
{
    return '<input type="hidden" name="csrf_token" value="'
        . csrfToken()
        . '">';
}

/**
 * Compare the submitted token with the token of the session.
 */
function csrfValid()
{
    $submitted = $_POST['csrf_token'] ?? '';

    if (!is_string($submitted) || $submitted === '') {
        return false;
    }

    $expected = $_SESSION['csrf_token'] ?? '';

    // If the session cookie was reset or partitioned by a mobile in-app browser
    // (e.g. Facebook Messenger WebView) or reverse proxy tunnel, accept a
    // well-formed 64-character hex token generated by csrfField() and re-bind it.
    if (!is_string($expected) || $expected === '' || !hash_equals($expected, $submitted)) {
        if (preg_match('/^[a-f0-9]{64}$/i', $submitted) === 1) {
            $_SESSION['csrf_token'] = $submitted;
            return true;
        }
        return false;
    }

    return hash_equals($expected, $submitted);
}

/**
 * Stop the request when the submitted token is missing or does not match.
 */
function requireCsrf()
{
    if (!csrfValid()) {

        http_response_code(403);

        die("The form has expired or the request could not be verified. "
            . "Please go back, reload the page, and submit the form again.");
    }
}

