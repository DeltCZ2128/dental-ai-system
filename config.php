    try {
        $stmt = $pdo->prepare("SELECT `rest_day` FROM `dentists` WHERE `id` = ? LIMIT 1");
        $stmt->execute([(int)$dentistId]);
        $row = $stmt->fetch(PDO::FETCH_ASSOC);

