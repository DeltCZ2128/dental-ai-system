/* Day number (0-6) to day name. Returns '' for none/invalid. */
function dentistRestDayName($restDay)
{
    $names = [
        0 => 'Sunday',
        1 => 'Monday',
        2 => 'Tuesday',
        3 => 'Wednesday',
        4 => 'Thursday',
        5 => 'Friday',
