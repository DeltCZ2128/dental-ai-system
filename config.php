/*
|--------------------------------------------------------------------------
| CLINIC GMAIL SENDER (REMINDERS)
|--------------------------------------------------------------------------
| Minimal SMTP + STARTTLS client for Gmail. No external library.
| Returns [bool $ok, string $error].
*/
function sendClinicGmail($toEmail, $subject, $body, $isHtml = false)
{
    $toEmail = trim((string)$toEmail);

    if (!filter_var($toEmail, FILTER_VALIDATE_EMAIL)) {
        return [false, 'Invalid patient email address.'];
    }

    $user = trim((string)CLINIC_SMTP_USER);
    $pass = trim((string)CLINIC_SMTP_PASS);

    if ($user === '' || $pass === '') {
        return [false, 'Email is not configured. Set the App Password locally first.'];
    }

    $host = CLINIC_SMTP_HOST;
    $port = (int)CLINIC_SMTP_PORT;
    $fromName = CLINIC_SMTP_FROM_NAME;

    $subject = trim((string)$subject) === '' ? 'Appointment Reminder' : trim((string)$subject);
    $body = (string)$body;

    $socket = @fsockopen($host, $port, $errno, $errstr, 4); // reduced from 15s to fail fast

    if (!$socket) {
        return [false, 'Could not connect to email server.'];
    }

    stream_set_timeout($socket, 4); // reduced from 15s to fail fast

    $readResponse = function () use ($socket) {
        $data = '';
        while (($line = fgets($socket, 515)) !== false) {
            $data .= $line;
            if (preg_match('/^\d{3} /', $line)) {
                break;
            }
        }
        return $data;
    };

    $sendCommand = function ($command) use ($socket, $readResponse) {
        fwrite($socket, $command . "\r\n");
        return $readResponse();
    };

    $readResponse();

    $response = $sendCommand('EHLO localhost');

    if (strpos($response, '250') === false) {
        fclose($socket);
        return [false, 'Email server rejected connection.'];
    }

    $response = $sendCommand('STARTTLS');

    if (strpos($response, '220') === false) {
        fclose($socket);
        return [false, 'Email server refused secure connection.'];
    }

    $crypto = @stream_socket_enable_crypto($socket, true, STREAM_CRYPTO_METHOD_TLS_CLIENT);

    if (!$crypto) {
        fclose($socket);
        return [false, 'Could not secure email connection.'];
    }

    $response = $sendCommand('EHLO localhost');

    if (strpos($response, '250') === false) {
        fclose($socket);
        return [false, 'Email server rejected connection.'];
    }

    $response = $sendCommand('AUTH LOGIN');

    if (strpos($response, '334') === false) {
        fclose($socket);
        return [false, 'Email login was rejected.'];
    }

    $response = $sendCommand(base64_encode($user));

    if (strpos($response, '334') === false) {
        fclose($socket);
        return [false, 'Email username was rejected.'];
    }

    $response = $sendCommand(base64_encode($pass));

    if (strpos($response, '235') === false) {
        fclose($socket);
        return [false, 'Email password was rejected. Check the App Password.'];
    }

    $encodedSubject = '=?UTF-8?B?' . base64_encode($subject) . '?=';
    $encodedBody = chunk_split(base64_encode($body));

    $contentType = $isHtml ? 'text/html; charset=UTF-8' : 'text/plain; charset=UTF-8';

    $headers =
        'From: ' . $fromName . ' <' . $user . ">\r\n" .
        'To: <' . $toEmail . ">\r\n" .
        // Eksplisitong address ng clinic kung saan dapat pumasok ang reply ng patient.
        'Reply-To: ' . $fromName . ' <' . $user . ">\r\n" .
        'Subject: ' . $encodedSubject . "\r\n" .
        'MIME-Version: 1.0' . "\r\n" .
        'Content-Type: ' . $contentType . "\r\n" .
        'Content-Transfer-Encoding: base64' . "\r\n";

    $response = $sendCommand('MAIL FROM:<' . $user . '>');

    if (strpos($response, '250') === false) {
        fclose($socket);
        return [false, 'Email sender was rejected.'];
    }

    $response = $sendCommand('RCPT TO:<' . $toEmail . '>');

    if (strpos($response, '250') === false && strpos($response, '251') === false) {
        fclose($socket);
        return [false, 'Patient email was rejected by the server.'];
    }

    $response = $sendCommand('DATA');

    if (strpos($response, '354') === false) {
        fclose($socket);
        return [false, 'Email server refused message content.'];
    }

    fwrite($socket, $headers . "\r\n" . $encodedBody . "\r\n.\r\n");
    $response = $readResponse();

    $sendCommand('QUIT');
    fclose($socket);

    if (strpos($response, '250') === false) {
        return [false, 'Email was not accepted by the server.'];
    }

    return [true, ''];
}

