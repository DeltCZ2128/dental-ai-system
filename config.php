function autoAppointmentReminders()
{
    global $pdo;

    try {
        if (trim((string)CLINIC_SMTP_PASS) === '') {
            return;
        }

        // Rate-limit: only attempt SMTP reminders once every 5 minutes.
        // This prevents 30-60s page hangs when the system clock is changed
        // (which causes TLS cert validation to fail, holding the socket open).
        $lockFile = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'dental_reminder_tick.txt';
        if (file_exists($lockFile) && (time() - filemtime($lockFile)) < 300) {
            return; // Last run was less than 5 minutes ago – skip silently
        }
        @file_put_contents($lockFile, date('Y-m-d H:i:s'));


        $stmt = $pdo->prepare("
            SELECT
                a.id,
                a.patient_id,
                a.appointment_date,
                a.start_time,
                a.service_type,
                a.status,
                CONCAT(COALESCE(p.first_name, ''), ' ', COALESCE(p.last_name, '')) AS patient_name,
                p.email AS patient_email
            FROM appointments a
            LEFT JOIN patients p ON p.id = a.patient_id
            WHERE a.appointment_date IN (
                DATE_ADD(CURDATE(), INTERVAL 3 DAY),
                DATE_ADD(CURDATE(), INTERVAL 2 DAY),
                DATE_ADD(CURDATE(), INTERVAL 1 DAY)
            )
            AND a.status IN ('Pending', 'Confirmed')
        ");

        $stmt->execute();
        $upcoming = $stmt->fetchAll(PDO::FETCH_ASSOC);

        if (empty($upcoming)) {
            return;
        }

        $today = date('Y-m-d');

        $sentTodayStmt = $pdo->prepare("
            SELECT id
            FROM notifications
            WHERE appointment_id = ?
            AND title = 'Auto Reminder'
            AND DATE(created_at) = ?
            LIMIT 1
        ");

        $countStmt = $pdo->prepare("
            SELECT COUNT(*)
            FROM notifications
            WHERE appointment_id = ?
            AND title = 'Auto Reminder'
        ");

        $replyStmt = $pdo->prepare("
            SELECT id
            FROM appointment_concerns
            WHERE appointment_id = ?
            LIMIT 1
        ");

        $logStmt = $pdo->prepare("
            INSERT INTO notifications
            (patient_id, appointment_id, title, message, type)
            VALUES (?, ?, ?, ?, ?)
        ");

        $cancelStmt = $pdo->prepare("
            UPDATE appointments
            SET status = 'Cancelled'
            WHERE id = ?
            AND status IN ('Pending', 'Confirmed')
        ");

        foreach ($upcoming as $appt) {
            $appointmentId = (int)$appt['id'];
            $patientEmail = trim((string)($appt['patient_email'] ?? ''));

            if ($patientEmail === '' || !filter_var($patientEmail, FILTER_VALIDATE_EMAIL)) {
                continue;
            }

            $daysLeft = (int)round(
                (strtotime($appt['appointment_date']) - strtotime($today)) / 86400
            );

            if (!in_array($daysLeft, [3, 2, 1], true)) {
                continue;
            }

            $sentTodayStmt->execute([$appointmentId, $today]);

            if ($sentTodayStmt->fetch()) {
                continue;
            }

            $countStmt->execute([$appointmentId]);
            $remindersSent = (int)$countStmt->fetchColumn();

            $replyStmt->execute([$appointmentId]);
            $hasReply = (bool)$replyStmt->fetch();

            $patientName = trim((string)($appt['patient_name'] ?? '')) === ''
                ? 'Patient'
                : trim((string)$appt['patient_name']);

            $appointmentTime = date('h:i A', strtotime($appt['start_time']));

            $subject = 'Appointment Reminder (' . $daysLeft . ' day' .
                ($daysLeft === 1 ? '' : 's') . ' left) - Abalos Dental Clinic';

            $message =
                "Hello " . $patientName . ",\n\n" .
                "Reminder from Abalos Dental Clinic.\n\n" .
                "Your appointment is in " . $daysLeft . " day" .
                ($daysLeft === 1 ? '' : 's') . ":\n" .
                "Date: " . $appt['appointment_date'] . "\n" .
                "Time: " . $appointmentTime . "\n" .
                "Service: " . (string)($appt['service_type'] ?? '') . "\n\n" .
                "Please confirm you are coming via your patient dashboard " .
                "(\"I'm Coming\" button) or contact the clinic.\n" .
                "If we receive no reply after 2 reminders, " .
                "the appointment will be automatically cancelled.\n\n" .
                "Thank you.";

            list($sent, $sendError) = sendClinicGmail($patientEmail, $subject, $message);

            if (!$sent) {
                continue;
            }

            try {
                $logStmt->execute([
                    (int)$appt['patient_id'],
                    $appointmentId,
                    'Auto Reminder',
                    'Day-' . $daysLeft . ' auto reminder sent to ' . $patientEmail . '.',
                    'Appointment'
                ]);
            } catch (PDOException $e) {
                continue;
            }

            $remindersSent++;

            if ($daysLeft === 2 && $remindersSent >= 2 && !$hasReply) {
                $cancelStmt->execute([$appointmentId]);

                if ($cancelStmt->rowCount() > 0) {
                    try {
                        $logStmt->execute([
                            (int)$appt['patient_id'],
                            $appointmentId,
                            'Appointment Cancelled',
                            'Appointment on ' . $appt['appointment_date'] . ' at ' . $appointmentTime . ' was automatically cancelled after 2 reminders with no reply.',
                            'Appointment'
                        ]);
                    } catch (PDOException $e) {
                    }
                }
            }
        }
    } catch (Throwable $e) {
        // Background tick must never break page loads.
    }
}

