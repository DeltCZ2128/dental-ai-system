/* "Dr. Renz" at "Renz" ay ituturing na pareho. */
function normalizeDentistNameForMatch($name)
{
    $name = strtolower(trim((string)$name));
    $name = preg_replace('/^dr\.?\s*/i', '', $name);
    $name = preg_replace('/\s+/', ' ', $name);
    return trim($name);
}

/*
 * I-resolve ang dentists.id mula sa logged-in user.
 * Returns int (0 kapag walang match - hindi dapat mangyari kapag naka-link).
 * Never throws.
 */
function resolveDentistId($userId, $fullName = '')
{
    global $pdo;

    $userId = (int)$userId;
    $fullName = trim((string)$fullName);

    try {
        // 1) Opisyal na link: dentists.user_id = users.id
        if ($userId > 0) {
            try {
                $stmt = $pdo->prepare("SELECT `id` FROM `dentists` WHERE `user_id` = ? LIMIT 1");
                $stmt->execute([$userId]);
                $hit = $stmt->fetchColumn();
                if ($hit) {
                    return (int)$hit;
                }
            } catch (Throwable $e) {
                // Kapag wala pang user_id column, tumuloy sa name match.
            }
        }

        // 2) Pangalan (normalized, "Dr." insensitive)
        if ($fullName !== '') {
            $want = normalizeDentistNameForMatch($fullName);
            if ($want !== '') {
                $rows = $pdo->query("SELECT `id`, `dentist_name` FROM `dentists`")->fetchAll(PDO::FETCH_ASSOC);
                foreach ($rows as $row) {
                    if (normalizeDentistNameForMatch($row['dentist_name'] ?? '') === $want) {
                        // I-link na rin para sa susunod na login.
                        try {
                            if ($userId > 0) {
                                $link = $pdo->prepare("UPDATE `dentists` SET `user_id` = ? WHERE `id` = ? AND (`user_id` IS NULL OR `user_id` = 0)");
                                $link->execute([$userId, (int)$row['id']]);
                            }
                        } catch (Throwable $e) {
                        }
                        return (int)$row['id'];
                    }
                }
            }
        }

        // 3) Fallback: users.id == dentists.id (lumang data)
        if ($userId > 0) {
            $stmt = $pdo->prepare("SELECT `id` FROM `dentists` WHERE `id` = ? LIMIT 1");
            $stmt->execute([$userId]);
            $hit = $stmt->fetchColumn();
            if ($hit) {
                try {
                    $link = $pdo->prepare("UPDATE `dentists` SET `user_id` = ? WHERE `id` = ? AND (`user_id` IS NULL OR `user_id` = 0)");
                    $link->execute([$userId, (int)$hit]);
                } catch (Throwable $e) {
                }
                return (int)$hit;
            }
        }
    } catch (Throwable $e) {
    }

    return 0;
}

/*
 * Siguraduhing may dentists row ang isang dentist user. Gumawa kapag wala,
 * i-link kapag may kaparehong pangalan. Returns dentists.id (0 kapag fail).
 */
function ensureDentistProfileForUser($userId, $fullName, $specialization = 'General Dentistry')
{
    global $pdo;

    $userId = (int)$userId;
    $fullName = trim((string)$fullName);
    if ($userId <= 0 || $fullName === '') {
        return 0;
    }

    ensureDentistUserIdColumn();

    $found = resolveDentistId($userId, $fullName);
    if ($found > 0) {
        return $found;
    }

    try {
        $stmt = $pdo->prepare("INSERT INTO `dentists` (`dentist_name`, `specialization`, `contact_number`, `status`, `user_id`) VALUES (?, ?, '', 'Active', ?)");
        $stmt->execute([$fullName, trim((string)$specialization) === '' ? 'General Dentistry' : trim((string)$specialization), $userId]);
        return (int)$pdo->lastInsertId();
    } catch (Throwable $e) {
        return 0;
    }
}

